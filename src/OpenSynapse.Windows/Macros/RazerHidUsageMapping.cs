    private static readonly Dictionary<byte, int> UsageToScancodeTable = BuildReverse();

    public static bool TryGetUsage(int scancode, out byte usage) =>
        ScancodeToUsageTable.TryGetValue(Normalize(scancode), out usage);

    public static bool TryGetScancode(byte usage, out int scancode) =>
        UsageToScancodeTable.TryGetValue(usage, out scancode);

    public static int Normalize(int scancode)
    {
        if (scancode is < 0 or > 0xFFFF)
        {
            return -1;
        }

        return scancode <= 0xFF
            ? scancode
            : (scancode & 0xE000) switch
            {
                0xE000 or 0xE100 => scancode,
                _ => -1,
            };
    }

    private static Dictionary<byte, int> BuildReverse()
    {
        var reverse = new Dictionary<byte, int>(ScancodeToUsageTable.Count);
        foreach (var pair in ScancodeToUsageTable)
        {
            reverse.TryAdd(pair.Value, pair.Key);
        }

        return reverse;
    }
