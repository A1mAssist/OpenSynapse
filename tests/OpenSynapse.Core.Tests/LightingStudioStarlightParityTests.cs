    [Fact]
    public void StarlightMatchesTheNativeOracleFrameSequence()
    {
        var parameters = OracleParameters();
        var input = new StudioEffectInput(StarlightSeed: OracleSeed);

        for (var tick = 0; tick < OracleFrames.Length; tick++)
        {
            var frame = StudioEffectRenderer.Render(parameters, 3, 3, tick / 25d, input);
            Assert.Equal(ToRgb(OracleFrames[tick]), frame[8]);
            for (var led = 0; led < 9; led++)
            {
                if (led != 8)
                {
                    Assert.Equal(StudioRgb.Black, frame[led]);
                }
            }
        }
    }

    [Fact]
    public void StarlightMatchesTheNativeMultiStarOracle()
    {
        var parameters = OracleParameters();
        parameters.Density = 10;
        AssertFullFrames(parameters, 3_921_880_744, MultiStarFrames);
    }

    [Fact]
    public void StarlightRandomColorMatchesTheNativeOracle()
    {
        var parameters = OracleParameters();
        parameters.Density = 10;
        parameters.RandomColor = true;
        AssertFullFrames(parameters, 3_921_880_775, RandomColorFrames);
    }

    [Fact]
    public void StarlightAtDensityOneLightsASingleStar()
    {
        var parameters = StudioEffectCatalog.CreateDefault(StudioEffectKind.Starlight);

        for (var tick = 0; tick < 120; tick++)
        {
            var frame = StudioEffectRenderer.Render(parameters, 3, 3, tick / 25d);
            Assert.True(frame.Count(pixel => pixel != StudioRgb.Black) <= 1, $"tick {tick}");
        }
    }

    [Fact]
    public void StarlightAtDensityTenFillsMostOfTheMatrix()
    {
        var parameters = StudioEffectCatalog.CreateDefault(StudioEffectKind.Starlight);
        parameters.Density = 10;
        var mostLit = 0;

        for (var tick = 0; tick < 120; tick++)
        {
            var frame = StudioEffectRenderer.Render(parameters, 3, 3, tick / 25d);
            mostLit = Math.Max(mostLit, frame.Count(pixel => pixel != StudioRgb.Black));
        }

        Assert.True(mostLit >= 5, $"only {mostLit} LEDs were ever lit");
    }

    [Fact]
    public void StarlightWithoutASeedIsDeterministic()
    {
        var left = StudioEffectCatalog.CreateDefault(StudioEffectKind.Starlight);
        var right = StudioEffectCatalog.CreateDefault(StudioEffectKind.Starlight);

        for (var tick = 0; tick < 60; tick++)
        {
            var first = StudioEffectRenderer.Render(left, 6, 17, tick / 25d);
            var second = StudioEffectRenderer.Render(right, 6, 17, tick / 25d);
            Assert.Equal(first.Length, second.Length);
            for (var led = 0; led < first.Length; led++)
            {
                Assert.Equal(first[led], second[led]);
            }
        }
    }

    private static void AssertFullFrames(
        StudioEffectParams parameters,
        uint seed,
        uint[] expected)
    {
        var input = new StudioEffectInput(StarlightSeed: seed);
        for (var tick = 0; tick < expected.Length / 9; tick++)
        {
            var frame = StudioEffectRenderer.Render(parameters, 3, 3, tick / 25d, input);
            for (var led = 0; led < frame.Length; led++)
            {
                Assert.Equal(ToRgb(expected[tick * 9 + led]), frame[led]);
            }
        }
    }

    private static StudioEffectParams OracleParameters()
    {
        var parameters = new StudioEffectParams
        {
            Effect = StudioEffectKind.Starlight,
            Density = 1,
            DurationMs = 1_700,
        };
        parameters.ColorStops.Add(new StudioColorStop(0, new StudioRgb(0xFF, 0x00, 0x00)));
        parameters.ColorStops.Add(new StudioColorStop(26, new StudioRgb(0xFF, 0xF3, 0x00)));
        parameters.ColorStops.Add(new StudioColorStop(42, new StudioRgb(0x36, 0xFF, 0x48)));
        parameters.ColorStops.Add(new StudioColorStop(55, new StudioRgb(0x62, 0xF1, 0xFF)));
        parameters.ColorStops.Add(new StudioColorStop(68, new StudioRgb(0x00, 0x0C, 0xFF)));
        parameters.ColorStops.Add(new StudioColorStop(81, new StudioRgb(0x80, 0x00, 0xFF)));
        parameters.ColorStops.Add(new StudioColorStop(100, new StudioRgb(0xFF, 0x00, 0x00)));
        return parameters;
    }

    private static StudioRgb ToRgb(uint value) =>
        new((byte)(value >> 16), (byte)(value >> 8), (byte)value);
